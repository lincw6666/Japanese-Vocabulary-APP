def main():
    new_words = []
    
    # 2. 解析原始資料轉換為 Dict
    for line in raw_data.strip().split('\n'):
        parts = line.split('|')
        if len(parts) == 8:
            word = {
                "id": parts[0],
                "kanji": parts[1],
                "kana": parts[2],
                "meaning": parts[3],
                "accent": int(parts[4]),
                "example": parts[5],
                "notes": parts[6],
                "correct": 0,
                "wrong": 0,
                "categories": parts[7].split(',') if parts[7] else []
            }
            new_words.append(word)

    file_name = 'vocab_N5.js'

    # 3. 讀取並注入到現有的 JS 檔案中
    if os.path.exists(file_name):
        with open(file_name, 'r', encoding='utf-8') as f:
            content = f.read()
            
        # 使用 Regex 找出原本的陣列位置
        match = re.search(r'(window\.VOCAB_DB\.N5\s*=\s*)(\[.*\]);?', content, re.DOTALL)
        if match:
            existing_vocab = json.loads(match.group(2))
            existing_vocab.extend(new_words) # 將新單字合併進去
            
            # 轉換回格式化過的美觀 JSON 字串
            new_array_json = json.dumps(existing_vocab, ensure_ascii=False, indent=4)
            new_content = content[:match.start(2)] + new_array_json + ";\n"
            
            # 覆寫原本的檔案
            with open(file_name, 'w', encoding='utf-8') as f:
                f.write(new_content)
            print(f"✅ 大成功！已將 {len(new_words)} 個新單字無縫擴充至 {file_name}。")
        else:
            print("❌ 無法解析檔案結構，請確認 window.VOCAB_DB.N5 是否存在。")
    else:
        # 防呆機制：如果找不到 js 檔，就先產生純 json 檔讓你複製
        with open('new_words.json', 'w', encoding='utf-8') as f:
            f.write(json.dumps(new_words, ensure_ascii=False, indent=4))
        print("⚠️ 找不到 vocab_N5.js！已備份轉換結果至 new_words.json 供您手動複製。")

if __name__ == "__main__":
    main()