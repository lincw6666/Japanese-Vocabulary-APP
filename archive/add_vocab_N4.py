def main():
    new_words = []
    
    # 逐行解析資料
    for line in raw_data.strip().split('\n'):
        if not line:
            continue
            
        parts = line.split('|')
        if len(parts) == 8:
            word = {
                "id": parts[0],
                "kanji": parts[1],
                "kana": parts[2],
                "meaning": parts[3],
                "accent": int(parts[4]),
                "example": parts[5],
                "notes": parts[6],
                "correct": 0,
                "wrong": 0,
                "categories": parts[7].split(',') if parts[7] else []
            }
            new_words.append(word)

    file_name = 'vocab_N4.js'
    
    # 👉 智慧判斷：如果檔案不存在，就幫你建立並加上 JSON 開頭
    if not os.path.exists(file_name):
        init_content = "window.VOCAB_DB = window.VOCAB_DB || {};\n\nwindow.VOCAB_DB.N4 = [\n];\n"
        with open(file_name, 'w', encoding='utf-8') as f:
            f.write(init_content)
        print(f"🆕 偵測到 {file_name} 不存在，已自動建立並初始化！")

    # 讀取並注入新單字
    with open(file_name, 'r', encoding='utf-8') as f:
        content = f.read()
        
    # 使用 Regex 找出 N4 陣列位置
    match = re.search(r'(window\.VOCAB_DB\.N4\s*=\s*)(\[.*\]);?', content, re.DOTALL)
    if match:
        existing_vocab = json.loads(match.group(2))
        existing_vocab.extend(new_words)
        
        new_array_json = json.dumps(existing_vocab, ensure_ascii=False, indent=4)
        new_content = content[:match.start(2)] + new_array_json + ";\n"
        
        with open(file_name, 'w', encoding='utf-8') as f:
            f.write(new_content)
        print(f"✅ 大成功！已將 {len(new_words)} 個 N4 新單字無縫擴充至 {file_name}。")
    else:
        print(f"❌ 無法解析檔案結構，請確認 {file_name} 裡是否有 window.VOCAB_DB.N4 = [];")

if __name__ == "__main__":
    main()