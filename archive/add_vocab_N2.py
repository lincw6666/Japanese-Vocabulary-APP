def get_seen_kanjis():
    """讀取 N5 和 N4 和 N3 的單字庫，收集已經出現過的漢字"""
    seen = set()
    for level in ['N5', 'N4', 'N3']:
        file_name = f'vocab_{level}.js'
        if os.path.exists(file_name):
            with open(file_name, 'r', encoding='utf-8') as f:
                content = f.read()
                # 抓取陣列內容
                match = re.search(rf'(window\.VOCAB_DB\.{level}\s*=\s*)(\[.*\]);?', content, re.DOTALL)
                if match:
                    vocab_list = json.loads(match.group(2))
                    for word in vocab_list:
                        seen.add(word['kanji'])
    return seen

def main():
    # 1. 取得已經在 N4, N5 出現過的漢字集合 (黑名單)
    seen_kanjis = get_seen_kanjis()
    
    new_words = []
    # 2. 逐行解析傳入的 raw_data
    for line in raw_data.strip().split('\n'):
        if not line:
            continue
            
        parts = line.split('|')
        if len(parts) == 8:
            word = {
                "id": "", # 👉 這裡先留空，等一下會統一重新編號
                "kanji": parts[1],
                "kana": parts[2],
                "meaning": parts[3],
                "accent": int(parts[4]),
                "example": parts[5],
                "notes": parts[6],
                "correct": 0,
                "wrong": 0,
                "categories": parts[7].split(',') if parts[7] else []
            }
            new_words.append(word)

    file_name = 'vocab_N2.js'
    existing_vocab = []
    
    # 3. 讀取現有的 N2 單字庫 (如果存在)
    if os.path.exists(file_name):
        with open(file_name, 'r', encoding='utf-8') as f:
            content = f.read()
        match = re.search(r'(window\.VOCAB_DB\.N2\s*=\s*)(\[.*\]);?', content, re.DOTALL)
        if match:
            existing_vocab = json.loads(match.group(2))
    else:
        # 初始化檔案結構
        content = "window.VOCAB_DB = window.VOCAB_DB || {};\n\nwindow.VOCAB_DB.N2 = [\n];\n"
        match = re.search(r'(window\.VOCAB_DB\.N2\s*=\s*)(\[.*\]);?', content, re.DOTALL)

    # 4. 合併並過濾重複單字
    final_n2_words = []
    
    # 先處理原本就已經寫入 N2 的單字
    for word in existing_vocab:
        if word['kanji'] not in seen_kanjis:
            final_n2_words.append(word)
            seen_kanjis.add(word['kanji']) # 加入黑名單，避免 N2 內部自己重複
            
    # 再處理剛從 raw_data 抓出來的新單字
    for word in new_words:
        if word['kanji'] not in seen_kanjis:
            final_n2_words.append(word)
            seen_kanjis.add(word['kanji'])

    # 5. 👉 終極絕招：統一重新編號 (確保絕對連續不斷號)
    for i, word in enumerate(final_n2_words):
        word['id'] = f"N2_{i+1:03d}"

    # 6. 寫回檔案
    new_array_json = json.dumps(final_n2_words, ensure_ascii=False, indent=4)
    new_content = content[:match.start(2)] + new_array_json + ";\n"
    
    with open(file_name, 'w', encoding='utf-8') as f:
        f.write(new_content)
        
    print(f"✅ 處理完成！過濾掉與 N4/N5 重複的單字後，目前 {file_name} 共有 {len(final_n2_words)} 個單字，且編號已自動連續重整。")

if __name__ == "__main__":
    main()